export const CLOSING_MATCHING_TYPES: Record<string, MatchingType> = Object.fromEntries(
  MATCHING_TYPE_ROWS.flatMap((row, r) => row.map((type, c) => [`${r + 1}-${c + 1}`, type] as const)),
);

// 선택한 감정 2개(선택 순서 그대로)의 매칭 유형 - 클러스터를 못 찾으면 null (임의 기본값을 만들지 않음)
export function getMatchingType(firstEmotionName: string | undefined, secondEmotionName: string | undefined): (MatchingType & { code: string }) | null {
  const cluster1 = firstEmotionName ? getDetailClusterForEmotionName(firstEmotionName.trim()) : undefined;
  const cluster2 = secondEmotionName ? getDetailClusterForEmotionName(secondEmotionName.trim()) : undefined;
  if (!cluster1 || !cluster2) return null;
  const code = `${cluster1.code}-${cluster2.code}`;
  const type = CLOSING_MATCHING_TYPES[code];
  return type ? { ...type, code } : null;
}

// 사용자가 "선택한 순서 그대로" 감정 2개를 넣으면 코드("A-B")를 만들어 멘트를 찾아줌.
// 순서를 정렬하거나 바꾸지 않음 - "1-2"와 "2-1"은 다른 문구.
// 상황(situation)은 여기서 전혀 쓰지 않음 - 오직 선택한 두 감정의 클러스터만으로 결정.
export function getClosingMessage(
  firstEmotionName: string | undefined,
  secondEmotionName: string | undefined,
): ClosingMessageLookupResult {
  const first = firstEmotionName?.trim();
  const second = secondEmotionName?.trim();

  if (!first || !second) {
    return { code: null, message: null, error: `감정 선택이 2개가 아닙니다: [${first ?? ''}, ${second ?? ''}]` };
  }

  const cluster1 = getDetailClusterForEmotionName(first);
  if (!cluster1) {
    return { code: null, message: null, error: `알 수 없는 감정 태그(클러스터 매핑 없음): "${first}"` };
  }

  const cluster2 = getDetailClusterForEmotionName(second);
  if (!cluster2) {
    return { code: null, message: null, error: `알 수 없는 감정 태그(클러스터 매핑 없음): "${second}"` };
  }

  const code = `${cluster1.code}-${cluster2.code}`;
  const message = CLOSING_MENTS[code];
  if (!message) {
    return { code, message: null, error: `클로징 멘트 코드 누락: "${code}"` };
  }

  return { code, message, error: null };
}
